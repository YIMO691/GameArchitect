#!/usr/bin/env python3
"""Build the lab pages.

Each lab is written once as a page fragment in demos/src/<name>.html: it starts with
<title>, <meta>, <link> and <style>, then the page content, then <script>.
No <!doctype>, <html>, <head> or <body> tags.

This script wraps every fragment into a complete HTML page for GitHub Pages:
    demos/src/index.html            -> demos/index.html
    demos/src/001-zombie-horde.html -> demos/001-zombie-horde/index.html

Usage:  python3 tools/build-demos.py
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "demos" / "src"
OUT = ROOT / "demos"

HEAD = (
    "<!doctype html>\n"
    "<html lang=\"en\">\n"
    "<meta charset=\"utf-8\">\n"
    "<meta name=\"viewport\" content=\"width=device-width, initial-scale=1, viewport-fit=cover\">\n"
    "<!-- Generated by tools/build-demos.py from demos/src/. Edit the source, not this file. -->\n"
)


def build() -> None:
    for src in sorted(SRC.glob("*.html")):
        body = src.read_text(encoding="utf-8")
        target = OUT / "index.html" if src.stem == "index" else OUT / src.stem / "index.html"
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(HEAD + body.lstrip() + ("" if body.endswith("\n") else "\n"), encoding="utf-8")
        print("built", target.relative_to(ROOT))


if __name__ == "__main__":
    build()
